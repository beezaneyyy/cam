_ALIASES = {"−": "-", "—": "-", "–": "-", "›": ">", "‹": "<", "⊗": "X", "Ø": "0"}

GLYPHS: dict[str, np.ndarray] = {
    ch: np.array([[c == "#" for c in row] for row in rows.split("|")], dtype=bool) for ch, rows in _RAW.items()
}
ROWS, COLS = 7, 5


def normalize(text: str) -> str:
    out = []
    for ch in text:
        ch = _ALIASES.get(ch, ch)
        if ch not in GLYPHS:
            up = ch.upper()
            if up in GLYPHS:
                ch = up
            else:
                base = unicodedata.normalize("NFD", up)[0]
                ch = base if base in GLYPHS else "?"
        out.append(ch)
    return "".join(out)


def bitmap(text: str, bold: bool = False) -> np.ndarray:
    """(7, width) boolean bitmap of ``text`` with 1-column letter spacing."""
    text = normalize(text)
    if not text:
        return np.zeros((ROWS, 1), bool)
    cols = []
    for i, ch in enumerate(text):
        cols.append(GLYPHS[ch])
        if i < len(text) - 1:
            cols.append(np.zeros((ROWS, 1), bool))
    bmp = np.hstack(cols)
    if bold:
        bmp = np.hstack([bmp, np.zeros((ROWS, 1), bool)])
        bmp[:, 1:] |= bmp[:, :-1]
    return bmp


@lru_cache(maxsize=1024)
def _render(text: str, color: tuple, scale: int, bold: bool) -> pygame.Surface:
    bmp = bitmap(text, bold)
    pad = 1  # one empty row above and below → line height 9 units
    h, w = (ROWS + 2 * pad) * scale, bmp.shape[1] * scale
    big = np.kron(bmp, np.ones((scale, scale), bool))
    rgba = np.zeros((h, w, 4), np.uint8)
    rgba[pad * scale: pad * scale + big.shape[0], :, :3] = color[:3]
    rgba[pad * scale: pad * scale + big.shape[0], :, 3] = np.where(big, color[3] if len(color) > 3 else 255, 0)
    return pygame.image.frombytes(rgba.tobytes(), (w, h), "RGBA")


class PixelFont:
    """Drop-in for the subset of ``pygame.font.Font`` the UI uses."""

    def __init__(self, size: int, bold: bool = False):
        # consistent steps: body text = 1 pixel unit, headings = 2, big numbers ≈ size/10
        self.scale = 1 if size < 12 else 2 if size < 24 else max(3, round(size / 10))
        self.bold = bold

    def render(self, text: str, antialias: bool = False, color=(255, 255, 255), background=None) -> pygame.Surface:
        return _render(str(text), tuple(int(c) for c in color), self.scale, self.bold).copy()

    def size(self, text: str) -> tuple[int, int]:
        n = len(normalize(str(text)))
        w = max(1, n * (COLS + 1) - 1 + (1 if self.bold else 0)) * self.scale
        return w, self.get_height()

    def get_height(self) -> int:
        return (ROWS + 2) * self.scale

    def get_bold(self) -> bool:
        return self.bold

    def set_bold(self, value: bool) -> None:
        self.bold = bool(value)


def clear_cache() -> None:
    _render.cache_clear()
